"""Writes docs/validation_report.md from check results."""

from src.common import DOCS
from src.validate.checks import CheckResult

MAX_ROWS = 40


def write(results: list[CheckResult], vintage: str) -> None:
    lines = [
        "# Validation report",
        "",
        f"Generated by `make validate`. CIMT data vintage (download date): {vintage}.",
        "",
        "Status: PASS = within tolerance; FAIL = outside tolerance (halting checks stop the "
        "pipeline); FLAG = outside tolerance, reviewed but not halting; LOG = recorded only.",
        "",
        "| ID | Check | Halts on failure | Status | Summary |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(f"| {r.check_id} | {r.title} | {'yes' if r.halting else 'no'} | "
                     f"**{r.status}** | {r.summary} |")
    for r in results:
        lines += ["", f"## {r.check_id}: {r.title}", "", f"Status: **{r.status}**. {r.summary}"]
        if r.note:
            lines += ["", r.note]
        if not r.details.empty:
            shown = r.details.head(MAX_ROWS)
            lines += ["", shown.to_markdown(index=False, floatfmt=",.4f")]
            if len(r.details) > MAX_ROWS:
                lines += ["", f"({len(r.details) - MAX_ROWS} more rows not shown.)"]
    (DOCS / "validation_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
